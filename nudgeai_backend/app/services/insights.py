"""Progress numbers, computed deterministically from habits and tasks.

Pure functions over small fact records, so every figure the Progress screens and the weekly report
show can be unit-tested without a database. Nothing here is generated by a model; a model may later
*phrase* an insight from these numbers, never invent them.

Conventions: ``today`` is the user's local date; windows end today and run backwards; bucket series
are oldest first; percentages are whole numbers 0-100.
"""

from __future__ import annotations

import calendar
from collections import Counter
from dataclasses import dataclass, field
from datetime import date, datetime, timedelta
from typing import Literal

Period = Literal["weekly", "monthly"]
DayStatus = Literal["completed", "some", "missed", "today", "future"]

WEEK = 7
MONTH_BUCKETS = 4  # four 7-day buckets, "Wk 1" the oldest
CONSISTENCY_WINDOW = 30
WEEKDAYS = ["Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday", "Sunday"]


@dataclass(frozen=True, slots=True)
class HabitFacts:
    id: str
    name: str
    emoji: str
    goal_days: int
    completions: frozenset[date]


@dataclass(frozen=True, slots=True)
class TaskFacts:
    id: str
    title: str
    day: date | None
    start_time: str | None
    due_at: datetime | None
    done_at: datetime | None


@dataclass(frozen=True, slots=True)
class Bar:
    label: str
    value: int


def _pct(part: float, whole: float) -> int:
    return 0 if whole <= 0 else max(0, min(100, round(part / whole * 100)))


def _days_back(today: date, n: int) -> list[date]:
    """The last ``n`` days ending today, oldest first."""
    return [today - timedelta(days=n - 1 - i) for i in range(n)]


def _buckets(period: Period, today: date) -> list[tuple[str, list[date]]]:
    if period == "weekly":
        return [(d.strftime("%a"), [d]) for d in _days_back(today, WEEK)]
    days = _days_back(today, WEEK * MONTH_BUCKETS)
    return [(f"Wk {i + 1}", days[i * WEEK : (i + 1) * WEEK]) for i in range(MONTH_BUCKETS)]


# ------------------------------------------------------------------------ habits


def habit_bars(habits: list[HabitFacts], today: date, period: Period) -> list[Bar]:
    """Share of possible check-ins actually done in each bucket (every habit, every day)."""
    out: list[Bar] = []
    for label, days in _buckets(period, today):
        done = sum(1 for h in habits for d in days if d in h.completions)
        out.append(Bar(label, _pct(done, len(habits) * len(days))))
    return out


def active_days(habits: list[HabitFacts]) -> set[date]:
    return set().union(*(h.completions for h in habits)) if habits else set()


def overall_streak(habits: list[HabitFacts], today: date) -> tuple[int, int]:
    """(current, best): consecutive days with any check-in; yesterday keeps the run alive."""
    days = sorted(active_days(habits))
    if not days:
        return 0, 0
    best = run = 1
    for prev, cur in zip(days, days[1:], strict=False):
        run = run + 1 if (cur - prev).days == 1 else 1
        best = max(best, run)
    alive = today - timedelta(days=1) <= days[-1] <= today
    return (run if alive else 0), best


def consistency(habits: list[HabitFacts], today: date) -> int:
    """Percent of recent days with at least one check-in.

    The window is the last 30 days, shortened to start at the first check-in so a brand new user
    isn't marked down for days before they began.
    """
    days = active_days(habits)
    if not days:
        return 0
    first = min(days)
    window = min(CONSISTENCY_WINDOW, (today - first).days + 1)
    recent = {d for d in days if today - timedelta(days=window - 1) <= d <= today}
    return _pct(len(recent), window)


@dataclass(frozen=True, slots=True)
class TopHabit:
    id: str
    name: str
    emoji: str
    streak: int
    completion: int


def _habit_streak(h: HabitFacts, today: date) -> int:
    current, _ = overall_streak([h], today)
    return current


def top_habits(habits: list[HabitFacts], today: date, n: int = 3) -> list[TopHabit]:
    """Best performers over 30 days: check-ins against the habit's own weekly goal."""
    window = set(_days_back(today, CONSISTENCY_WINDOW))
    ranked = []
    for h in habits:
        done = len(h.completions & window)
        expected = h.goal_days * CONSISTENCY_WINDOW / WEEK
        ranked.append(
            TopHabit(h.id, h.name, h.emoji, _habit_streak(h, today), _pct(done, expected))
        )
    ranked.sort(key=lambda t: (-t.completion, -t.streak, t.name))
    return ranked[:n]


def consistency_map(habits: list[HabitFacts], today: date) -> list[tuple[date, DayStatus]]:
    """This calendar month, day by day: all habits done, some, none, today, or still ahead."""
    count = len(habits)
    out: list[tuple[date, DayStatus]] = []
    for day_no in range(1, calendar.monthrange(today.year, today.month)[1] + 1):
        d = date(today.year, today.month, day_no)
        if d > today:
            status: DayStatus = "future"
        elif d == today:
            status = "today"
        else:
            done = sum(1 for h in habits if d in h.completions)
            status = "missed" if done == 0 else "completed" if done >= count else "some"
        out.append((d, status))
    return out


# ------------------------------------------------------------------------- tasks


def _in_range(t: TaskFacts, days: set[date]) -> bool:
    return t.day is not None and t.day in days


def task_bars(tasks: list[TaskFacts], today: date, period: Period) -> list[Bar]:
    out: list[Bar] = []
    for label, days in _buckets(period, today):
        scoped = [t for t in tasks if _in_range(t, set(days))]
        out.append(Bar(label, _pct(sum(1 for t in scoped if t.done_at), len(scoped))))
    return out


@dataclass(frozen=True, slots=True)
class TaskOverview:
    done: int
    total: int
    completion_rate: int
    on_time_rate: int
    overdue: int


def task_overview(tasks: list[TaskFacts], today: date, now: datetime) -> TaskOverview:
    week = set(_days_back(today, WEEK))
    scoped = [t for t in tasks if _in_range(t, week)]
    done = [t for t in scoped if t.done_at]
    timed = [t for t in done if t.due_at]
    on_time = sum(1 for t in timed if t.done_at and t.due_at and t.done_at <= t.due_at)
    overdue = sum(1 for t in tasks if not t.done_at and t.due_at and t.due_at < now)
    return TaskOverview(
        done=len(done),
        total=len(scoped),
        completion_rate=_pct(len(done), len(scoped)),
        on_time_rate=_pct(on_time, len(timed)),
        overdue=overdue,
    )


@dataclass(frozen=True, slots=True)
class TimeGroup:
    name: Literal["Morning", "Afternoon", "Evening"]
    completion: int
    total: int


def _time_group(start: str) -> Literal["Morning", "Afternoon", "Evening"]:
    hour = int(start[:2])
    return "Morning" if hour < 12 else "Afternoon" if hour < 17 else "Evening"


def task_time_groups(tasks: list[TaskFacts], today: date) -> list[TimeGroup]:
    """Completion by time of day over 30 days (all-day tasks have no time of day)."""
    window = set(_days_back(today, CONSISTENCY_WINDOW))
    totals: Counter[str] = Counter()
    done: Counter[str] = Counter()
    for t in tasks:
        if t.start_time and _in_range(t, window):
            group = _time_group(t.start_time)
            totals[group] += 1
            done[group] += 1 if t.done_at else 0
    return [
        TimeGroup(name, _pct(done[name], totals[name]), totals[name])
        for name in ("Morning", "Afternoon", "Evening")
    ]


@dataclass(frozen=True, slots=True)
class OverdueTask:
    id: str
    title: str
    due_at: datetime
    days_overdue: int


def most_overdue(
    tasks: list[TaskFacts], today: date, now: datetime, n: int = 5
) -> list[OverdueTask]:
    out: list[tuple[datetime, TaskFacts, date]] = []
    for t in tasks:
        if not t.done_at and t.due_at and t.due_at < now and t.day is not None:
            out.append((t.due_at, t, t.day))
    out.sort(key=lambda row: row[0])
    return [OverdueTask(t.id, t.title, due, max(1, (today - day).days)) for due, t, day in out[:n]]


# ------------------------------------------------------------------ weekly report


@dataclass(frozen=True, slots=True)
class WeeklyReport:
    habit_rate: int
    check_ins: int
    possible: int
    tasks_done: int
    tasks_total: int
    best_day: str | None
    best_day_count: int
    top_habit: str | None
    needs_love: str | None
    headline: str
    tips: list[str] = field(default_factory=list)


def _headline(rate: int, has_habits: bool) -> str:
    if not has_habits:
        return "Add a habit to get your first report"
    if rate >= 80:
        return "A great week. You’re in a real rhythm"
    if rate >= 50:
        return "A solid week with room to grow"
    if rate > 0:
        return "A quieter week. Small steps still count"
    return "A fresh start. Check in a habit today"


def weekly_report(habits: list[HabitFacts], tasks: list[TaskFacts], today: date) -> WeeklyReport:
    week = set(_days_back(today, WEEK))
    possible = sum(h.goal_days for h in habits)
    counts = [(h, len(h.completions & week)) for h in habits]
    check_ins = sum(c for _, c in counts)
    rate = _pct(check_ins, possible)

    scoped = [t for t in tasks if _in_range(t, week)]
    overdue_this_week = sum(1 for t in scoped if not t.done_at)

    per_day: Counter[date] = Counter(d for h in habits for d in h.completions if d in week)
    best = max(per_day.items(), key=lambda kv: (kv[1], kv[0]), default=None)
    best_name = WEEKDAYS[best[0].weekday()] if best else None

    ranked = sorted(counts, key=lambda hc: -hc[1])
    top = ranked[0][0].name if ranked and ranked[0][1] > 0 else None
    lowest = ranked[-1] if ranked else None
    needs = (
        lowest[0].name
        if lowest and len(ranked) > 1 and lowest[0].name != top and lowest[1] < lowest[0].goal_days
        else None
    )

    tips: list[str] = []
    if needs and top:
        tips.append(f"Try stacking “{needs}” right after “{top}”.")
    elif needs:
        tips.append(f"Give “{needs}” a fixed time of day.")
    if best_name:
        tips.append(f"{best_name} is your strongest day. Plan your hardest habit then.")
    if overdue_this_week:
        s = "" if overdue_this_week == 1 else "s"
        tips.append(f"{overdue_this_week} task{s} from this week still need a new time.")
    if not tips:
        tips.append("Keep going. Consistency matters more than intensity.")

    return WeeklyReport(
        habit_rate=rate,
        check_ins=check_ins,
        possible=possible,
        tasks_done=sum(1 for t in scoped if t.done_at),
        tasks_total=len(scoped),
        best_day=best_name,
        best_day_count=best[1] if best else 0,
        top_habit=top,
        needs_love=needs,
        headline=_headline(rate, bool(habits)),
        tips=tips[:3],
    )
